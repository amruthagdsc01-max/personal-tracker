import { useEffect, useRef, useState } from 'react'
import { Send } from 'lucide-react'
import { BY_ID, LESSONS } from '../../data/sd/index.js'
import { mentorReply } from '../../domain/sd/engine.js'
import { api, STATIC } from '../../api.js'
import { sdGo } from './useSd.js'

const STARTERS = ['Explain this in simpler words', 'Give me a real-world example', 'When should I not use this?', 'Give me a hint for the challenge', 'Quiz me with a follow-up question', 'Interview me on this']

/**
 * A mentor that answers ONLY from the lessons on this platform (nothing invented), with honest "I don't know"
 * when a topic is not covered. If the server has an LLM key configured (optional), "Ask the AI mentor" is enabled
 * and the same lesson text is sent as the only allowed source.
 */
export default function Mentor({ S, arg }) {
  const [lessonId, setLessonId] = useState(arg && BY_ID[arg] ? arg : '')
  const [msgs, setMsgs] = useState([{ who: 'mentor', text: 'Ask me about any lesson. I answer only from this platform\'s own content, I will say so when something is not covered, and I give hints before answers. I cannot mark anything as learned: only your quizzes and explanations do that.' }])
  const [q, setQ] = useState('')
  const [reveal, setReveal] = useState(null)
  const [ai, setAi] = useState({ available: false, busy: false })
  const end = useRef()
  useEffect(() => { end.current?.scrollIntoView({ block: 'nearest' }) }, [msgs])
  useEffect(() => { if (!STATIC && S.token) api('/mentor/status').then((r) => setAi((a) => ({ ...a, available: !!r?.enabled }))).catch(() => {}) }, [S.token])

  const ask = (text) => {
    const t = text.trim(); if (!t) return
    const r = mentorReply(t, { lessonId: lessonId || null, sd: S.sd, date: S.date })
    setMsgs((m) => [...m, { who: 'you', text: t }, { who: 'mentor', ...r }])
    setReveal(r.reveal || null)
    S.logMentor({ lessonId: r.sources[0] || lessonId || null, hint: !!r.hint, date: S.date })
    setQ('')
  }
  const askAi = async () => {
    const t = q.trim(); if (!t) return
    const ctx = (lessonId ? [BY_ID[lessonId]] : []).concat(mentorReply(t, {}).sources.map((s) => BY_ID[s])).filter(Boolean).slice(0, 2)
    const context = ctx.map((l) => `# ${l.title}\n${l.levels.map((v) => v.body.join('\n')).join('\n')}\n${l.connects}`).join('\n\n')
    setAi((a) => ({ ...a, busy: true })); setMsgs((m) => [...m, { who: 'you', text: t }]); setQ('')
    try {
      const r = await api('/mentor', { method: 'POST', token: S.token, body: { question: t, context } })
      setMsgs((m) => [...m, { who: 'mentor', text: r.answer, sources: ctx.map((l) => l.id), ai: true }])
    } catch (e) { setMsgs((m) => [...m, { who: 'mentor', text: `The AI mentor is not available right now (${e.message}). The built-in mentor still works.` }]) }
    setAi((a) => ({ ...a, busy: false }))
  }

  return (
    <div className="sd-mentor">
      <header className="p-head"><p className="kicker">Mentor</p><h1>Ask, get a hint, find the gap.</h1></header>
      <div className="m-ctx"><label>Talking about<select value={lessonId} onChange={(e) => setLessonId(e.target.value)}><option value="">Anything on the platform</option>{LESSONS.map((l) => <option key={l.id} value={l.id}>{l.title}</option>)}</select></label></div>
      <div className="chat" role="log" aria-live="polite" aria-label="Conversation with the mentor">
        {msgs.map((m, i) => (
          <div key={i} className={`msg ${m.who}`}><p>{m.text}</p>
            {m.sources?.length > 0 && <small>From: {m.sources.map((s) => <button key={s} className="link" onClick={() => sdGo(`lesson/${s}`)}>{BY_ID[s].title}</button>).reduce((a, b) => [a, ', ', b])}{m.ai ? ' · generated by the optional AI mentor from this lesson text' : ''}</small>}
            {m.followUp && <button className="btn ghost sm" onClick={() => ask(m.followUp)}>Think about: {m.followUp.slice(0, 70)}…</button>}
            {m.action === 'interview' && m.sources[0] && <button className="btn ghost sm" onClick={() => sdGo(`interview/iq-${m.sources[0]}`)}>Open interview mode</button>}
          </div>))}
        <div ref={end} />
      </div>
      {reveal && <div className="row"><button className="btn ghost sm" onClick={() => { setMsgs((m) => [...m, { who: 'mentor', text: `Answer: ${reveal}` }]); setReveal(null) }}>Reveal the answer</button><span className="muted">Try first.</span></div>}
      <div className="starters">{STARTERS.map((s) => <button key={s} className="chip" onClick={() => ask(s)}>{s}</button>)}</div>
      <form className="ask-form" onSubmit={(e) => { e.preventDefault(); ask(q) }}>
        <label className="sr" htmlFor="mq">Your question</label>
        <input id="mq" value={q} onChange={(e) => setQ(e.target.value)} placeholder="e.g. Why does a cache help the database? What is idempotency?" />
        <button className="btn primary sm" type="submit" disabled={!q.trim()}><Send size={14} /> Ask</button>
        {ai.available && <button className="btn ghost sm" type="button" onClick={askAi} disabled={!q.trim() || ai.busy}>{ai.busy ? 'Thinking…' : 'Ask the AI mentor'}</button>}
      </form>
      <p className="muted">{ai.available ? 'The optional AI mentor is enabled on this server and is told to use only the lesson text.' : STATIC ? 'AI mentor: unavailable in the static GitHub Pages build (it needs a server). The built-in mentor works offline.' : 'AI mentor: not configured. It needs you to be logged in and MENTOR_API_KEY set on the server (see README). The built-in mentor works without it.'}</p>
    </div>
  )
}
